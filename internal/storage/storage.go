// Package storage keeps uploaded files (resumes, later audio) encrypted at rest.
// Files are AES-256-GCM encrypted before they touch disk, so a copied disk or
// backup reveals nothing without APP_ENCRYPTION_KEY.
package storage

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"

	"github.com/markzugenjer/ai-screener-interview-backend/internal/security"
)

type Files interface {
	// Put encrypts and stores data; owner is bound into the ciphertext.
	Put(ctx context.Context, data []byte, ext, owner string) (key string, err error)
	Get(ctx context.Context, key, owner string) ([]byte, error)
	Delete(ctx context.Context, key string) error
}

var (
	ErrBadKey   = errors.New("invalid file key")
	ErrNotFound = errors.New("file not found")
	keyPattern  = regexp.MustCompile(`^[a-f0-9]{32}\.(pdf|docx|ogg|webm|bin)\.enc$`)
)

type Local struct {
	dir string
	enc *security.Encryptor
}

func NewLocal(dir string, enc *security.Encryptor) (*Local, error) {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return nil, fmt.Errorf("create storage dir: %w", err)
	}
	return &Local{dir: dir, enc: enc}, nil
}

func (l *Local) path(key string) (string, error) {
	// Keys are generated by us and strictly validated, so no "../" path tricks are possible.
	if !keyPattern.MatchString(key) {
		return "", ErrBadKey
	}
	return filepath.Join(l.dir, key[:2], key), nil
}

func (l *Local) Put(_ context.Context, data []byte, ext, owner string) (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	key := hex.EncodeToString(b) + ext + ".enc"
	p, err := l.path(key)
	if err != nil {
		return "", err
	}
	sealed, err := l.enc.Encrypt(data, []byte("file:"+owner))
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o700); err != nil {
		return "", err
	}
	tmp := p + ".tmp"
	if err := os.WriteFile(tmp, sealed, 0o600); err != nil {
		return "", err
	}
	return key, os.Rename(tmp, p)
}

func (l *Local) Get(_ context.Context, key, owner string) ([]byte, error) {
	p, err := l.path(key)
	if err != nil {
		return nil, err
	}
	sealed, err := os.ReadFile(p)
	if errors.Is(err, os.ErrNotExist) {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	return l.enc.Decrypt(sealed, []byte("file:"+owner))
}

func (l *Local) Delete(_ context.Context, key string) error {
	p, err := l.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(p); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}
